#!/usr/bin/env node
/* ──────────────────────────────────────────────────────────────────────
   把模板/渲染器搬进 Functions 可用形态 · embed_assets.mjs
   ──────────────────────────────────────────────────────────────────────
   为什么需要：Cloudflare Pages Functions 里没有 fs，读不到 templates/*.html；
   但后台要「贴 JD 一键出变体」，就必须在边缘侧渲染同一套模板。

   做法：把模板序列化成 JS 字符串常量，把 render_resume.mjs 里的纯函数段
   切出来当模块，二者都生成到 functions/lib/ 下 —— 单一真相源仍然是
   templates/resume.template.html 与 scripts/render_resume.mjs，
   这里只是构建产物，不要手改。

   用法：
     node scripts/embed_assets.mjs           生成
     node scripts/embed_assets.mjs --check   只比对（CI 用，漂移退出码 1）
   ────────────────────────────────────────────────────────────────────── */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = resolve(ROOT, 'templates/resume.template.html');
const RENDERER = resolve(ROOT, 'scripts/render_resume.mjs');
const SITE_DATA = resolve(ROOT, 'data/site-data.json');
const OUT_DIR = resolve(ROOT, 'functions/lib');

const check = process.argv.includes('--check');

function buildTemplate() {
  const raw = readFileSync(TEMPLATE, 'utf8');
  return '/* AUTO-GENERATED by scripts/embed_assets.mjs — 勿手改 */\n' +
    '/* 源文件：templates/resume.template.html */\n' +
    'export const TEMPLATE = ' + JSON.stringify(raw) + ';\n';
}

function buildSiteData() {
  const raw = readFileSync(SITE_DATA, 'utf8');
  JSON.parse(raw); // 顺便校验格式，坏 JSON 别等到部署才炸
  return '/* AUTO-GENERATED by scripts/embed_assets.mjs — 勿手改 */\n' +
    '/* 源文件：data/site-data.json（唯一真相源） */\n' +
    'export default ' + raw.trim() + ';\n';
}

function buildRenderer() {
  const src = readFileSync(RENDERER, 'utf8');
  const start = src.indexOf('const BANNER = [');
  const end = src.indexOf('export { render };');
  if (start < 0 || end < 0) throw new Error('render_resume.mjs 结构变了，embed 切片失败');
  let body = src.slice(start, end);
  /* 模板从常量来，不再读盘 */
  body = body.replace("const tpl = readFileSync(TEMPLATE_FILE, 'utf8');", 'const tpl = TEMPLATE;');
  const head = '/* AUTO-GENERATED by scripts/embed_assets.mjs — 勿手改 */\n' +
    '/* 源文件：scripts/render_resume.mjs（只搬运纯渲染函数，不含 CLI 与文件 IO） */\n' +
    "import { TEMPLATE } from './resume-template.js';\n\n";
  return head + body + "export { render };\n";
}

mkdirSync(OUT_DIR, { recursive: true });
const files = [
  ['resume-template.js', buildTemplate()],
  ['resume-render.js', buildRenderer()],
  ['site-data.js', buildSiteData()],
];

let drift = false;
for (const [name, content] of files) {
  const path = resolve(OUT_DIR, name);
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch (e) { current = ''; }
  if (current === content) {
    console.log(`✓ ${name} 已是最新`);
    continue;
  }
  if (check) {
    console.error(`✗ ${name} 与源文件不一致，请运行 node scripts/embed_assets.mjs`);
    drift = true;
    continue;
  }
  writeFileSync(path, content);
  console.log(`✓ 已生成 functions/lib/${name}（${Buffer.byteLength(content)} bytes）`);
}
if (drift) process.exit(1);
